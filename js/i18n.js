window.HumanityState = window.HumanityState || {
  lang: (function () {
    const raw = localStorage.getItem("humanity-lang") || "zh";
    if (raw === "zh-Hans" || raw === "zh-CN") return "zh";
    if (raw === "zh-Hant" || raw === "zh-TW") return "zh-TW";
    if (raw === "en" || raw === "zh" || raw === "zh-TW") return raw;
    return "zh";
  })(),
  theme: localStorage.getItem("humanity-theme") || "dark",
};

